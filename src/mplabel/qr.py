"""A QR encoder, in the stdlib, for inventory labels.

Hand-written for the same reason `lzma1.py` and the parcel-code overlay
are: the Pi dependency list is kept short on purpose, and a QR code is a
fixed, forty-year-old specification that will not change under us. Adding
a package to draw twenty-one squares would be the convenience this repo
has already decided against twice.

Scope is deliberately narrow - versions 1 to 10, which is up to 174
alphanumeric characters at level M. An inventory code is four characters
and fits in a version 1 at the highest error correction the format has,
so the range here is headroom for a URL, not ambition.

Correctness is not taken on trust. `test_qr_matches_a_reference_encoder`
pins whole matrices generated by `segno`, an independent implementation,
across every version, error-correction level and mode this module claims
to support. segno is not a dependency of anything - it was used once to
produce the fixtures and the fixtures are what the tests compare against.
"""

# The alphanumeric set, in the order that defines each character's value.
# Note it is not ASCII order and does not contain lowercase: a string
# with a lowercase letter in it is a byte-mode string, which costs about
# 40% more capacity.
ALPHANUMERIC = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ $%*+-./:"

MODE_ALNUM = 0b0010
MODE_BYTE = 0b0100

# Error-correction levels, in the order the format-information field
# numbers them - which is *not* increasing strength.
ECC_LEVELS = {"L": 0b01, "M": 0b00, "Q": 0b11, "H": 0b10}

# Per version: (error-correction codewords per block, [(block count,
# data codewords per block), ...]). Two groups where the blocks are not
# all the same size, which is most of them above version 4.
BLOCKS = {
    (1, "L"): (7, [(1, 19)]),    (1, "M"): (10, [(1, 16)]),
    (1, "Q"): (13, [(1, 13)]),   (1, "H"): (17, [(1, 9)]),
    (2, "L"): (10, [(1, 34)]),   (2, "M"): (16, [(1, 28)]),
    (2, "Q"): (22, [(1, 22)]),   (2, "H"): (28, [(1, 16)]),
    (3, "L"): (15, [(1, 55)]),   (3, "M"): (26, [(1, 44)]),
    (3, "Q"): (18, [(2, 17)]),   (3, "H"): (22, [(2, 13)]),
    (4, "L"): (20, [(1, 80)]),   (4, "M"): (18, [(2, 32)]),
    (4, "Q"): (26, [(2, 24)]),   (4, "H"): (16, [(4, 9)]),
    (5, "L"): (26, [(1, 108)]),  (5, "M"): (24, [(2, 43)]),
    (5, "Q"): (18, [(2, 15), (2, 16)]),
    (5, "H"): (22, [(2, 11), (2, 12)]),
    (6, "L"): (18, [(2, 68)]),   (6, "M"): (16, [(4, 27)]),
    (6, "Q"): (24, [(4, 19)]),   (6, "H"): (28, [(4, 15)]),
    (7, "L"): (20, [(2, 78)]),   (7, "M"): (18, [(4, 31)]),
    (7, "Q"): (18, [(2, 14), (4, 15)]),
    (7, "H"): (26, [(4, 13), (1, 14)]),
    (8, "L"): (24, [(2, 97)]),
    (8, "M"): (22, [(2, 38), (2, 39)]),
    (8, "Q"): (22, [(4, 18), (2, 19)]),
    (8, "H"): (26, [(4, 14), (2, 15)]),
    (9, "L"): (30, [(2, 116)]),
    (9, "M"): (22, [(3, 36), (2, 37)]),
    (9, "Q"): (20, [(4, 16), (4, 17)]),
    (9, "H"): (24, [(4, 12), (4, 13)]),
    (10, "L"): (18, [(2, 68), (2, 69)]),
    (10, "M"): (26, [(4, 43), (1, 44)]),
    (10, "Q"): (24, [(6, 19), (2, 20)]),
    (10, "H"): (28, [(6, 15), (2, 16)]),
}

# Centres of the alignment patterns. Version 1 has none; the finders are
# enough to locate a symbol that small.
ALIGNMENT = {
    1: [], 2: [6, 18], 3: [6, 22], 4: [6, 26], 5: [6, 30], 6: [6, 34],
    7: [6, 22, 38], 8: [6, 24, 42], 9: [6, 26, 46], 10: [6, 28, 50],
}

MAX_VERSION = 10


class QRError(ValueError):
    """The text does not fit, or cannot be encoded in a supported mode."""


